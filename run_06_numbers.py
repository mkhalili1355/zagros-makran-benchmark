def load(name):
    p = os.path.join(C.OUT_DIR, name)
    if not os.path.exists(p):
        return None
    with open(p) as f:
        return json.load(f)


def fmt(x, n=3):
    if x is None:
        return "n/a"
    if isinstance(x, (int, np.integer)):
        return "{:,}".format(x)
    try:
        return "{:.{}f}".format(float(x), n)
    except Exception:
        return str(x)


def sfmt(x, n=3):
    """Signed number rendered as TEXT, e.g. +0.012 / -0.004 / n/a.

    fmt() already returns a str, and a sign-aware format spec cannot be
    applied to a str: Python raises "Sign not allowed in string format
    specifier". So the sign has to be baked in here instead.
    """
    if x is None:
        return "n/a"
    try:
        v = float(x)
    except Exception:
        return str(x)
    return ("+" if v >= 0 else "-") + "{:.{}f}".format(abs(v), n)


def write_csv(name, header, rows):
    p = os.path.join(C.TAB_DIR, name)
    with open(p, "w", newline="") as f:
        wr = csv.writer(f)
        wr.writerow(header)
        wr.writerows(rows)
    print("   " + name)


